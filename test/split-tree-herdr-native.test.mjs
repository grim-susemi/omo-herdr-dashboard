const EXPECTED_SNAPSHOTS = 189;

async function replay(size, name) {
  const { area: [width, height], sequences: { [name]: sequence } } = NATIVE[size];
  // Herdr has no pane-size floor (S6), so the fake runs without one.
  const fake = createSplitTreeHerdr({ tree: 'chat', area: { x: 0, y: 0, width, height }, focused: 'chat', minSize: 0 });
  const alias = new Map([['chat', 'chat']]);
  const compare = (snapshot, index) => {
    const layout = fake.layout(), named = new Map([...alias].map(([native, id]) => [id, native]));
    const rects = Object.fromEntries(layout.panes.map(pane => [named.get(pane.pane_id),
      [pane.rect.x, pane.rect.y, pane.rect.width, pane.rect.height]]));
    const where = `${size} ${name} snapshot ${index}`;
    assert.deepEqual(rects, snapshot.rects, `${where}: rects`);
    assert.equal(named.get(layout.focused_pane_id), snapshot.focus, `${where}: focus`);
    assert.deepEqual(layout.splits.map(split => Math.fround(split.ratio)), snapshot.ratios.map(Math.fround),
      `${where}: stored ratios`);
  };
  compare(sequence.snapshots[0], 0);
  for (const [index, op] of sequence.ops.entries()) {
    const args = op.args.map(value => alias.get(value) ?? value);
    const result = await fake.herdr(...args);
    if (op.created) alias.set(op.created, result.pane.pane_id);
    compare(sequence.snapshots[index + 1], index + 1);
  }
  return sequence.snapshots.length;
}

let compared = 0;
for (const size of Object.keys(NATIVE))
  for (const name of Object.keys(NATIVE[size].sequences))
    test(`native replay ${name} at ${size} matches every recorded snapshot`, async () => {
      compared += await replay(size, name);
    });

test('the replays compared every recorded snapshot', () => {
  assert.equal(compared, EXPECTED_SNAPSHOTS);
});
